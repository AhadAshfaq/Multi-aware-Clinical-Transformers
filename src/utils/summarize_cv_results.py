"""Summarize five AP or NF fine-tuning fold-result files.

Reads locally generated, trusted pickle files only. Result files and other
MIMIC-IV-derived artifacts cannot be committed to this repository.
"""

from __future__ import annotations

import argparse
import pickle
from pathlib import Path

import numpy as np


METRIC_NAMES = ("ROC-AUC", "PR-AUC", "MinRP", "Max F1")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cohort", choices=("AP", "NF"), required=True)
    parser.add_argument(
        "--results-dir",
        type=Path,
        required=True,
        help="Directory containing this cohort's five FINAL_Chemo_*_Fold_*.pkl files.",
    )
    parser.add_argument(
        "--label-fraction",
        type=int,
        default=100,
        help="Key in each result dictionary; default: 100.",
    )
    args = parser.parse_args()

    if not args.results_dir.is_dir():
        parser.error(f"Results directory does not exist: {args.results_dir}")

    fold_values = []

    for fold in range(5):
        path = args.results_dir / f"FINAL_Chemo_{args.cohort}_Fold_{fold}.pkl"
        if not path.is_file():
            parser.error(f"Missing fold {fold} result: {path}")

        # Only load files generated by your own trusted fine-tuning runs.
        with path.open("rb") as handle:
            result = pickle.load(handle)

        if args.label_fraction not in result:
            parser.error(
                f"Label fraction {args.label_fraction} missing from {path}; "
                f"available keys: {list(result)}"
            )

        metrics = result[args.label_fraction]
        if len(metrics) != len(METRIC_NAMES):
            parser.error(f"Expected four metrics in {path}; found {len(metrics)}")

        try:
            means = np.asarray([entry[0] for entry in metrics], dtype=float)
        except (TypeError, ValueError, IndexError) as exc:
            parser.error(f"Malformed metric entries in {path}: {exc}")

        if not np.isfinite(means).all():
            parser.error(f"Non-finite metric value in {path}")

        fold_values.append(means)
        print(
            f"Fold {fold}: "
            + " | ".join(
                f"{name}={value:.4f}"
                for name, value in zip(METRIC_NAMES, means)
            )
        )

    values = np.stack(fold_values)
    print(f"\n{args.cohort}: mean ± SD across five folds")
    for metric_index, name in enumerate(METRIC_NAMES):
        print(
            f"{name}: {values[:, metric_index].mean():.4f} "
            f"± {values[:, metric_index].std(ddof=0):.4f}"
        )


if __name__ == "__main__":
    main()